"""Write macros/registry.sql: the list of pieces, read from their YAML files.

dbt applies a model's YAML (including `meta`) after it parses the SQL, and
the `graph` variable is empty while parsing. So a model can't discover the
pieces, or emit ref()s to them, from YAML alone. This script reads the YAML
files directly and writes the names into a macro that base/pieces calls, so
every piece gets a real ref() and appears in lineage.

    python scripts/build_registry.py

`make parse`, `make check` and `make build` run it first. base/pieces fails
at run time if the registry doesn't match the project's piece models.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "macros" / "registry.sql"


def model_names(directory: Path) -> list[str]:
    names = []
    for path in sorted(directory.rglob("*.yml")):
        document = yaml.safe_load(path.read_text()) or {}
        for model in document.get("models") or []:
            names.append(model["name"])
    return sorted(names)


def render(pieces: list[str]) -> str:
    return (
        "{#\n"
        "    Generated by scripts/build_registry.py from models/pieces/*.yml. Do not edit.\n"
        "    Run `make registry` after adding, renaming or removing a piece.\n"
        "#}\n"
        "\n"
        "{% macro registered_pieces() %}\n"
        f"    {{{{ return({pieces!r}) }}}}\n"
        "{% endmacro %}\n"
    )


def main() -> int:
    content = render(model_names(ROOT / "models" / "pieces"))
    if not REGISTRY_PATH.exists() or REGISTRY_PATH.read_text() != content:
        REGISTRY_PATH.write_text(content)
        print(f"registry: wrote {REGISTRY_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
