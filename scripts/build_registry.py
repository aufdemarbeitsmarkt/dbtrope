"""Write macros/registry.sql: the pieces and stored instruments, read from their YAML.

dbt applies a model's YAML (including `meta`) after it parses the SQL, and
the `graph` variable is empty while parsing. So a model can't discover the
pieces or instruments, or emit ref()s to them, from YAML alone. This script
reads the YAML files directly and writes the names into macros:

  - registered_pieces(): every model in models/pieces/, for base/pieces
  - registered_instruments(): every model in models/instruments/, for
    base/instruments
  - piece_instrument_uses(piece_name): the stored instruments a piece uses,
    which compose() turns into `-- depends_on` lines so lineage shows them

    python scripts/build_registry.py

`make parse`, `make check` and `make build` run it first. base/pieces and
base/instruments fail at run time if the registry doesn't match the project.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "macros" / "registry.sql"

# A voice without an `instrument:` plays this stored instrument.
DEFAULT_INSTRUMENT = "sine"


def models_in(directory: Path) -> dict[str, dict]:
    models = {}
    for path in sorted(directory.rglob("*.yml")):
        document = yaml.safe_load(path.read_text()) or {}
        for model in document.get("models") or []:
            models[model["name"]] = model
    return dict(sorted(models.items()))


def stored_instruments_used(piece: dict) -> list[str]:
    """Same lookup as base/piece_instruments: a voice's instrument is the
    piece's own declaration if there is one (which may `use:` a stored
    instrument), otherwise the stored instrument of that name."""
    meta = (piece.get("config") or {}).get("meta") or {}
    declared = meta.get("instruments") or {}
    used = set()
    for declaration in declared.values():
        if isinstance(declaration, dict) and declaration.get("use"):
            used.add(declaration["use"])
    for voice in meta.get("voices") or []:
        name = voice.get("instrument") or DEFAULT_INSTRUMENT
        if name not in declared:
            used.add(name)
    return sorted(used)


def render(pieces: dict[str, dict], instruments: dict[str, dict]) -> str:
    uses = {name: stored_instruments_used(piece) for name, piece in pieces.items()}
    uses_lines = "".join(f"        {name!r}: {used!r},\n" for name, used in uses.items())
    return (
        "{#\n"
        "    Generated by scripts/build_registry.py from models/pieces/*.yml and\n"
        "    models/instruments/*.yml. Do not edit. Run `make registry` after adding,\n"
        "    renaming or removing a piece or instrument, or changing which\n"
        "    instruments a piece uses.\n"
        "#}\n"
        "\n"
        "{% macro registered_pieces() %}\n"
        f"    {{{{ return({list(pieces)!r}) }}}}\n"
        "{% endmacro %}\n"
        "\n"
        "{% macro registered_instruments() %}\n"
        f"    {{{{ return({list(instruments)!r}) }}}}\n"
        "{% endmacro %}\n"
        "\n"
        "{% macro piece_instrument_uses(piece_name) %}\n"
        "    {%- set uses = {\n"
        f"{uses_lines}"
        "    } %}\n"
        "    {{ return(uses.get(piece_name, [])) }}\n"
        "{% endmacro %}\n"
    )


def main() -> int:
    content = render(
        models_in(ROOT / "models" / "pieces"),
        models_in(ROOT / "models" / "instruments"),
    )
    if not REGISTRY_PATH.exists() or REGISTRY_PATH.read_text() != content:
        REGISTRY_PATH.write_text(content)
        print(f"registry: wrote {REGISTRY_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
